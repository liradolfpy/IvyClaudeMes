def _expand(k,t,nul,ref):
    if ref=="(polymorphic)": return [(k,"String","(polymorphic)",nul),(k[:-2]+"Name","String",None,nul)]
    if k.endswith("ById"): return [(k,"String","user",nul),(k[:-2],"String",None,nul)]
    if k.endswith("Id"): return [(k,"String",ref,nul),(k[:-2]+"Name","String",None,nul)]
    return [(k,t,None,nul)]

