def apply(COLS):
    """Called by flatten_model.py: appends the new collections (numbered 1300+ by their position) and inserts the added keys."""
    byent={v["entity"]:v for v in COLS.values()}
    for c in NEW:
        fl=FIELDS[c["entity"]]; ks=[f[0] for f in fl]
        if c["kind"]=="entity": disp=next((d for d in ("name","title","description","fullName") if d in ks),"recordNo")
        else: disp="recordNo"
        pe=parent_entity(c)
        parentc=None
        if pe: parentc=collection_name(BYENT[pe]) if pe in BYENT else byent[pe]["collection"]
        COLS[collection_name(c)]=dict(collection=collection_name(c),module=c["module"],moduleName=MOD_NAMES[c["module"]],entity=c["entity"],sourceConcept=src_name(c,byent),
            kind=c["kind"],dataClass="master" if c["type"]=="Master" else "transaction",parent=parentc,displayField=disp,statusValues=c["status"] if c["kind"]=="entity" else None,
            fields=[dict(key=k,type=t,ref=r) for k,t,r,n in fl])
        byent[c["entity"]]=COLS[collection_name(c)]
    for e,k,t,nul,ref,en,d in ADD:
        col=byent[e]; keys=[f["key"] for f in col["fields"]]
        pos=keys.index("status") if "status" in keys else keys.index("schemaVersion")
        new=[dict(key=a,type=b,ref=r) for a,b,r,n in _expand(k,t,nul,ref)]
        for x in new: assert x["key"] not in keys,(e,x["key"])
        col["fields"][pos:pos]=new

