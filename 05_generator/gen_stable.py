def check(root, collections):
    screens = set(query_screens(root))
    ivy = {}
    for p in glob.glob(os.path.join(root, "04_reference_data", "ui_controls", "query", "IvyConfig", "*.json")):
        try:
            j = json.load(open(p, encoding="utf-8"))
            ivy[j["collection"]] = j["stableName"]
        except (ValueError, KeyError):
            pass
    findings = 0
    for c in collections:
        if not os.path.exists(os.path.join(root, TABLE_DIR, c + ".json")):
            print("MISSING    %s" % c)
            findings += 1
            continue
        res = check_file(root, c, screens, ivy)
        if res:
            findings += len(res)
            print("FAIL       %s: %s" % (c, "; ".join(res)))
    print("Checked %d files: %d findings" % (len(collections), findings))


