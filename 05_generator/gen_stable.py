# MongoDB shell style writer
# ---------------------------------------------------------------------------
def shell(v, ind=0):
    pad = " " * ind
    if isinstance(v, NumberInt):
        return "NumberInt(%d)" % v.v
    if isinstance(v, RawDoc):
        inner = (",\n").join(" " * (ind + 4) + json.dumps(k) + " : " + t for k, t in v.pairs)
        return "{\n" + inner + "\n" + pad + "}"
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "[]"
        inner = (",\n").join(" " * (ind + 4) + shell(x, ind + 4) for x in v)
        return "[\n" + inner + "\n" + pad + "]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        keys = sorted(v)
        if "clmnDoc" in v:                       # clmnDoc is always the last key (skill 0.5)
            keys = [k for k in keys if k != "clmnDoc"] + ["clmnDoc"]
        inner = (",\n").join(" " * (ind + 4) + json.dumps(k) + " : " + shell(v[k], ind + 4)
                          for k in keys)
        return "{\n" + inner + "\n" + pad + "}"
    raise TypeError(type(v))


def check_parse(text):
    """The written file must parse once the shell constructors are read as values."""
    t = re.sub(r'ISODate\("([^"]*)"\)', r'"\1"', text)
    t = re.sub(r'NumberDecimal\("([^"]*)"\)', r'"\1"', t)
    t = re.sub(r'NumberLong\("?(-?\d+)"?\)', r'\1', t)
    t = re.sub(r'NumberInt\((-?\d+)\)', r'\1', t)
    t = re.sub(r'Double\(([^)]*)\)', r'\1', t)
    json.loads(t)


