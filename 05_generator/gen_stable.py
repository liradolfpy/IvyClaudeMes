# Build, compare, report
# ---------------------------------------------------------------------------
TABLE_DIR = os.path.join("04_reference_data", "ui_controls", "table", "PageConfigs")
REL_RE = re.compile(r'"rel" : "[^"]*"')


def build(root, collection, rel):
    """Return (text, info) for one collection; raise Skip when it cannot be built."""
    fields = read_field_list(root, collection)
    page_title, screen_type, module_code = read_page_title(root, collection)
    samples, sp_path = read_samples(root, collection)
    if not sp_path:
        raise Skip("no sample file (clmnDoc needs the first sample document)")
    keyset = {f["key"] for f in fields}
    chosen, dropped = select_columns(fields)
    columns, report = [], []
    for i, f in enumerate(chosen):
        col, max_len = build_column(f, keyset, samples, i == 0)
        columns.append(col)
        report.append((i + 1, f["key"], col["title"], f["type"] + ("/" + f["tag"] if f["tag"] != "-" else ""),
                       max_len, col["width"], col["align"]))
    doc = build_document(collection, page_title, module_code, columns, read_first_sample_raw(sp_path), rel)
    text = shell(doc) + "\n"
    check_parse(text)
    info = {"title": page_title, "type": screen_type, "module": module_code, "samples": len(samples),
            "columns": len(columns), "width": sum(int(c["width"][:-2]) for c in columns),
            "report": report, "dropped": dropped,
            "no_sample": [r[1] for r in report if r[4] == 0],
            "no_display": [d[0] for d in dropped if d[1] == "reference key without a display key"],
            "_id": doc["_id"]}
    return text, info


def report_section(collection, info, rel):
    lines = ["## %s - %s (%s)" % (collection, info["title"], info["type"]), "",
             "File: %s/%s.json | _id: %s | rel: %s | samples: %d | columns: %d | total width: %dpx"
             % (TABLE_DIR.replace(os.sep, "/"), collection, info["_id"], rel, info["samples"],
                info["columns"], info["width"]), "",
             "| # | data_index | title | type | longest sample | width | align |", "|---|---|---|---|---|---|---|"]
    lines += ["| %d | %s | %s | %s | %d | %s | %s |" % r for r in info["report"]]
    lines += ["", "Left out: " + "; ".join("%s (%s)" % d for d in info["dropped"])]
    if info["no_sample"]:
        lines += ["", "No non-null sample value (width from title only): " + ", ".join(info["no_sample"])]
    return "\n".join(lines) + "\n\n"


def update_reports(root, sections):
    """Replace or add the run's sections in column_report_<module>.md; other sections stay."""
    by_module = {}
    for coll, text in sections.items():
        by_module.setdefault(module_of(coll), {})[coll] = text
    for mod, new in by_module.items():
        path = os.path.join(root, TABLE_DIR, "column_report_%s.md" % mod)
        old = {}
        if os.path.exists(path):
            for part in re.split(r"(?m)^(?=## u_)", open(path, encoding="utf-8").read()):
                m = re.match(r"## (u_\S+)", part)
                if m:
                    old[m.group(1)] = part.rstrip("\n") + "\n\n"
        old.update(new)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write("".join(old[k] for k in sorted(old)).rstrip("\n") + "\n")


def plain(text):
    """Shell style -> JSON with tagged constructor values, for comparison and checks."""
    t = re.sub(r'ISODate\("([^"]*)"\)', r'"ISO:\1"', text)
    t = re.sub(r'NumberDecimal\("([^"]*)"\)', r'"DEC:\1"', t)
    t = re.sub(r'NumberLong\("?(-?\d+)"?\)', r'"LONG:\1"', t)
    t = re.sub(r'NumberInt\((-?\d+)\)', r'"INT:\1"', t)
    t = re.sub(r'Double\(([^)]*)\)', r'"DBL:\1"', t)
    return json.loads(t)


def changed_paths(old, new, path="", out=None):
    out = [] if out is None else out
    if isinstance(old, dict) and isinstance(new, dict):
        for k in sorted(set(old) | set(new)):
            if k == "rel" and not path:
                continue
            if k not in old or k not in new:
                out.append(path + "." + k)
            else:
                changed_paths(old[k], new[k], path + "." + k, out)
    elif isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        for i, (a, b) in enumerate(zip(old, new)):
            changed_paths(a, b, "%s[%d]" % (path, i), out)
    elif old != new:
        out.append(path)
    return out


def run(root, collections, dry_run):
    rel = datetime.datetime.now(IST).strftime(RESP + "%Y%m%d-%H:%M")   # one value per run
    counts = {"NEW": 0, "CHANGED": 0, "UNCHANGED": 0, "SKIPPED": 0}
    skipped, no_sample, no_display, sections = [], [], [], {}
    out_dir = os.path.join(root, TABLE_DIR)
    os.makedirs(out_dir, exist_ok=True)
    for c in collections:
        try:
            text, info = build(root, c, rel)
        except Skip as e:
            counts["SKIPPED"] += 1
            skipped.append((c, str(e)))
            print("SKIPPED    %s  (%s)" % (c, e))
            continue
        path = os.path.join(out_dir, c + ".json")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old is None:
            status, detail = "NEW", ""
        elif REL_RE.sub("", old) == REL_RE.sub("", text):
            status, detail = "UNCHANGED", ""
        else:
            status = "CHANGED"
            try:
                cp = changed_paths(plain(old), plain(text))
                detail = "  changes: " + ", ".join(cp[:5]) + (" (+%d more)" % (len(cp) - 5) if len(cp) > 5 else "")
            except ValueError:
                detail = "  changes: existing file does not parse"
        counts[status] += 1
