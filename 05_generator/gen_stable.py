_FIELD_LISTS = {}
_MATRIX = {}


def _load_field_lists(root):
    if _FIELD_LISTS:
        return
    for path in sorted(glob.glob(os.path.join(root, "02_architecture", "field_lists", "*_field_list.md"))):
        current = None
        for line in open(path, encoding="utf-8").read().splitlines():
            if line.startswith("## "):
                current = line[3:].strip()
                _FIELD_LISTS[current] = []
                continue
            m = re.match(r"^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|\s*$", line)
            if m and current:
                _FIELD_LISTS[current].append({"no": int(m.group(1)), "key": m.group(2), "type": m.group(3),
                                              "tag": m.group(4), "ref": m.group(5)})


def read_field_list(root, collection):
    _load_field_lists(root)
    fields = _FIELD_LISTS.get(collection)
    if not fields:
        raise Skip("not found in any field list")
    return fields


def read_page_title(root, collection):
    """Screen label, screen type and module code from collection_type_matrix.md."""
    if not _MATRIX:
        path = os.path.join(root, "02_architecture", "collection_type_matrix.md")
        for line in open(path, encoding="utf-8"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 5 and cells[2].startswith("u_"):
                _MATRIX[cells[2]] = (cells[4], cells[3], cells[0])
    if collection not in _MATRIX:
        raise Skip("not found in collection_type_matrix.md")
    return _MATRIX[collection]


def query_screens(root):
    """Collections that have a query screen (skill 0.8: only these get a table)."""
    names = []
    for f in sorted(glob.glob(os.path.join(root, "04_reference_data", "ui_controls", "query", "PageConfigs", "*.json"))):
        n = os.path.basename(f)[:-5]
        if n.startswith("PageConfig_"):
            n = n[len("PageConfig_"):]
        if n.startswith("u_"):
            names.append(n)
    return names


def module_of(collection):
    return collection.split("_")[2]


def read_samples(root, collection):
    paths = glob.glob(os.path.join(root, "03_design", "*", "samples", collection + ".js"))
    if not paths:
        return [], None
    txt = open(paths[0], encoding="utf-8").read()
    body = txt[txt.index("insertMany(") + len("insertMany("):txt.rindex(")")]
    body = re.sub(r'ISODate\("([^"]*)"\)', r'"\1"', body)
    body = re.sub(r'NumberInt\((-?\d+)\)', r'\1', body)
    body = re.sub(r'NumberLong\("?(-?\d+)"?\)', r'\1', body)
    # Decimal128 is written as a plain number since 18 Oct 2026 (no NumberDecimal());
    # the substitution below only reads older sample files that still carry the constructor.
    body = re.sub(r'NumberDecimal\("([^"]*)"\)', r'"\1"', body)
    body = re.sub(r'Double\(([^)]*)\)', r'\1', body)
    body = re.sub(r'^(\s*)([A-Za-z_$][\w$]*)\s*:', r'\1"\2":', body, flags=re.M)
    body = re.sub(r',(\s*[}\]])', r'\1', body)
    return json.loads(body), paths[0]


def read_first_sample_raw(path):
    """First document of the samples file, as (key, value text) pairs in file order."""
    txt = open(path, encoding="utf-8").read()
    i = txt.index("{", txt.index("insertMany("))
    depth, j, in_str = 0, i, False
    while True:
        ch = txt[j]
        if in_str:
            if ch == "\\":
                j += 1
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                break
        j += 1
    pairs = []
    for line in txt[i + 1:j].splitlines():
        line = line.strip()
        if not line:
            continue
        m = re.match(r'^"?([A-Za-z_$][\w$]*)"?\s*:\s*(.*?),?$', line)
        if not m:
            raise Skip("cannot read sample line: " + line[:60])
        pairs.append((m.group(1), m.group(2)))
    return RawDoc(pairs)


